%a quick and dirty display script to look at behavior coding
%analysis results - S.T>.

globals = rhythmTap_globals;

behaveCoding = an{3}.results;
behaveCodingCols = set_var_col_const(behaveCoding.vars);

disp = ensemble_init_data_struct;

disp.vars = {'data' 'column_labels' 'column_formats'};
dispCols = set_var_col_const(disp.vars);

coder_time_min = floor(behaveCoding.data{behaveCodingCols.coder_time}./60);
coder_time_sec = mod(behaveCoding.data{behaveCodingCols.coder_time},60);

disp.data{dispCols.data} = ...
    {behaveCoding.data{behaveCodingCols.subject_id} ...
     behaveCoding.data{behaveCodingCols.trial_order} ...
     behaveCoding.data{behaveCodingCols.tapping_condition} ...
     behaveCoding.data{behaveCodingCols.coder_id} ...
     behaveCoding.data{behaveCodingCols.beh_prop_total} ...
     behaveCoding.data{behaveCodingCols.behavior_proportion} ...
     coder_time_min ...
     coder_time_sec ...
     behaveCoding.data{behaveCodingCols.trial_start_stop}(:,1) ...
     behaveCoding.data{behaveCodingCols.trial_start_stop}(:,2) ...
     behaveCoding.data{behaveCodingCols.beh_start_stop}(:,1) ...
     behaveCoding.data{behaveCodingCols.beh_start_stop}(:,2) ...
     behaveCoding.data{behaveCodingCols.behavior}};

disp.data{dispCols.column_labels} = {'subject_id' 'trial_num' 'tapping_condition' ...
		    'coder_id' 'beh_prop_total' 'beh_proportion' ...
		    'coder_min' 'coder_sec' 't_start' 't_end' 'b_start' 'b_end' 'behavior'};
disp.data{dispCols.column_formats} = {'%s' '%9d' '%17s' '%8d' '%14.2f' ...
		    '%14.2f' '%d' '%.1f' '%7.2f' '%5.2f' '%7.2f' '%5.2f' '%s'};

dispParams.fname = fullfile(globals.paths.logpath,'behaveCodingQuickResults_9July.txt');
dispParams.write2file = 1;

ensemble_display_table(disp,dispParams);
